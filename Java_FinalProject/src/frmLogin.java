    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String us = txtUsername.getText().trim();
        String ps = String.valueOf(txtPassword.getPassword()).trim();
        if (us.equals("")) {
            JOptionPane.showMessageDialog(this, "Username cannot be empty",
                    "Login System", JOptionPane.INFORMATION_MESSAGE);
        } else if (ps.equals("")) {
            JOptionPane.showMessageDialog(this, "Password cannot be empty",
                    "Login System", JOptionPane.INFORMATION_MESSAGE);
        } else {
            String displayNameFromFile = null;
            try {
                BufferedReader reader = new BufferedReader(new FileReader("src/user.txt"));
                String line;
                while ((line = reader.readLine()) != null) {
                    String[] userInfo = line.split(",");
                    displayNameFromFile = userInfo[1].trim();
                    String usernameFromFile = userInfo[2].trim();
                    String passwordFromFile = userInfo[3].trim();

                    if (us.equals(usernameFromFile) && ps.equals(passwordFromFile)) {
                        break;
                    }
                }
                reader.close();
            } catch (FileNotFoundException e) {
                e.printStackTrace();
            } catch (IOException e) {
                e.printStackTrace();
            }
            Icon icon = new javax.swing.ImageIcon(getClass().getResource("/images/check.png"));
                JOptionPane.showMessageDialog(null, "Login successful!","SUCCESS!!",JOptionPane.INFORMATION_MESSAGE,icon);
                DiceRollMain main = new DiceRollMain();
                main.setVisible(true);
                main.setLocationRelativeTo(null);
                this.dispose();
        }
        txtUsername.setText("");
        txtPassword.setText("");

    }//GEN-LAST:event_btnLoginActionPerformed

