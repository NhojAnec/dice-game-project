    private void btnRollActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRollActionPerformed
        String dieSide = txtCount.getText();
        try {
            if (Integer.parseInt(dieSide) == 0) {
                JOptionPane.showMessageDialog(this, "กรุณาใส่จำนวนหน้าลูกเต๋า", "Warning", JOptionPane.WARNING_MESSAGE);
            } else if (Integer.parseInt(dieSide) < 6 || Integer.parseInt(dieSide) > 999) {
                JOptionPane.showMessageDialog(this, "จำนวนหน้าลูกเต๋าต้องไม่น้อยกว่า 6 หรือมากกว่า 999", "Warning", JOptionPane.WARNING_MESSAGE);
            } else {
                String username = "user";
                String title = (super.getTitle() + "หน้า " + dieSide);
                DICE.setDieSide(Integer.parseInt(dieSide));
                int dieRoll1 = DICE.getRandomDieRoll();
                int dieRoll2 = DICE.getRandomDieRoll();
                lblNum1.setText(String.valueOf(dieRoll1));
                lblNum2.setText(String.valueOf(dieRoll2));
                lblResult.setText("คุณทอยได้ " + String.valueOf(dieRoll1) + " และ " + String.valueOf(dieRoll2));
                lblSum.setText("ผลรวมคือ " + (dieRoll1 + dieRoll2));
                btnRoll.setText("ทอยอีกครั้ง");
                BufferedWriter writer = new BufferedWriter(new FileWriter(filename, true));
                String twoD = (username + ";" + title + ";" + "(" + dieRoll1 + " + " + dieRoll2 + ")" + " = " + (dieRoll1 + dieRoll2) + "\n");
                writer.write(twoD);
                writer.close();
            }
        } catch (NumberFormatException nfe) {
            JOptionPane.showMessageDialog(this, "หน้าลูกเต๋าต้องเป็นตัวเลขเท่านั้น", "Warning", JOptionPane.WARNING_MESSAGE);
        } catch (IOException ex) {
            Logger.getLogger(TwoDice.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnRollActionPerformed

